import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createInventory } from './inventory.mjs';
import { validateItem } from './validation.mjs';
import { search } from './search.mjs';
import { summary } from './summary.mjs';
import { exportCsv } from './csv.mjs';
import { save, load } from './storage.mjs';
import { render } from './render.mjs';
test('inventory lifecycle', () => {
  const inv = createInventory();
  inv.add({ id: 'a', name: 'Apples', quantity: 2, price: 3 });
  inv.add({ id: 'b', name: 'Bread', quantity: 1, price: 4 });
  assert.throws(() => inv.add({ id: 'a', name: 'Other', quantity: 1, price: 1 }));
  inv.update('a', { quantity: 3 });
  assert.equal(summary(inv.list()).value, 13);
  assert.equal(summary(inv.list()).units, 4);
  assert.equal(search(inv.list(), 'APP')[0].id, 'a');
  assert.throws(() => inv.update('missing', {}));
  inv.remove('b');
  assert.equal(inv.list().length, 1);
  const copy = inv.list();
  copy[0].quantity = 99;
  assert.equal(inv.list()[0].quantity, 3);
});
test('validation and formats', () => {
  assert.throws(() => validateItem({ id: '', name: 'x', quantity: 1, price: 1 }));
  assert.throws(() => validateItem({ id: 'a', name: 'x', quantity: -1, price: 1 }));
  assert.throws(() => validateItem({ id: 'a', name: 'x', quantity: 1.5, price: 1 }));
  assert.throws(() => validateItem({ id: 'a', name: 'x', quantity: 1, price: NaN }));
  const rows = [{ id: 'a', name: 'Tea, "green"', quantity: 2, price: 3 }];
  assert.equal(exportCsv(rows), 'id,name,quantity,price\na,"Tea, ""green""",2,3\n');
  const memory = new Map();
  const adapter = { setItem: (k, v) => memory.set(k, v), getItem: (k) => memory.get(k) };
  save(adapter, rows);
  assert.deepEqual(load(adapter), rows);
  assert.deepEqual(load({ getItem: () => null }), []);
  assert.deepEqual(load({ getItem: () => '{' }), []);
  const html = render([{ ...rows[0], name: '<script>' }]);
  assert(html.includes('&lt;script&gt;'));
  assert(!html.includes('<script>'));
});
